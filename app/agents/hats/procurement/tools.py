# A plain number, after thousands separators are removed. Rejects anything
# float() would also reject, without catching the exception.
_PLAIN_NUMBER = re.compile(
    r"^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?$"
)

# One alias table for every BOQ row the generator reads. Canonical names win;
# an alias only fills a missing canonical field (setdefault).
_BOQ_FIELD_ALIASES = (
    ("quantity", ("qty",)),
    ("unit_price", ("rate", "unit_rate")),
    ("total", ("amount",)),
)
_BOQ_ROW_LISTS = ("boq", "line_items")


def _coerce_boq_number(value: Any) -> Any:
    """A BOQ cell as a number, or None when it is not numeric."""
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, (int, float)):
        return value
    if isinstance(value, str):
        text = value.strip().replace(",", "")
        if not _PLAIN_NUMBER.match(text):
            return None
        number = float(text)
        if "." not in text and "e" not in text.lower() and number.is_integer():
            return int(number)
        return number
    return None


def _normalise_boq_row(row: dict) -> dict:
    """Map qty/rate/amount onto quantity/unit_price/total. setdefault only."""
    out = dict(row)
    for dest, aliases in _BOQ_FIELD_ALIASES:
        if dest in out:
            number = _coerce_boq_number(out[dest])
            if number is not None:
                out[dest] = number
            continue
        for alias in aliases:
            if alias not in row:
                continue
            number = _coerce_boq_number(row[alias])
            if number is None:
                continue
            out.setdefault(dest, number)
            break
    return out


def _normalise_boq_lists(payload: dict) -> None:
    """Normalise every BOQ row list this tool is about to hand the generator."""
    if not isinstance(payload, dict):
        return
    for key in _BOQ_ROW_LISTS:
        rows = payload.get(key)
        if not isinstance(rows, list):
            continue
        payload[key] = [
            _normalise_boq_row(row) if isinstance(row, dict) else row
            for row in rows
        ]


